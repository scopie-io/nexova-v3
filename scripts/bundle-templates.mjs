#!/usr/bin/env node
/**
 * Snapshot every template under templates/ into packages/server/src/templates.bundle.ts so the
 * engine can compose sites on hosts without a template folder on disk (Vercel Functions).
 * Skips node_modules, dist and VCS folders; text files are stored as utf8, everything else base64.
 *
 *   node scripts/bundle-templates.mjs
 */
import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const templatesDir = path.join(root, "templates");
const outFile = path.join(root, "packages", "server", "src", "templates.bundle.ts");

const IGNORE = new Set(["node_modules", "dist", ".git", ".vite", ".cache", ".DS_Store", ".vercel", "package-lock.json"]);
const TEXT = /\.(json|js|mjs|cjs|ts|tsx|jsx|css|html|md|txt|svg|xml|yml|yaml|env|toml)$/i;

async function walk(dir, rel = "", out = {}) {
  for (const e of await fs.readdir(dir, { withFileTypes: true })) {
    if (IGNORE.has(e.name) || e.isSymbolicLink()) continue;
    const r = rel ? `${rel}/${e.name}` : e.name;
    if (e.isDirectory()) await walk(path.join(dir, e.name), r, out);
    else if (e.isFile()) {
      const data = await fs.readFile(path.join(dir, e.name));
      out[r] = TEXT.test(e.name) ? { encoding: "utf8", data: data.toString("utf8") } : { encoding: "base64", data: data.toString("base64") };
    }
  }
  return out;
}

const templates = [];
for (const name of (await fs.readdir(templatesDir, { withFileTypes: true })).filter((e) => e.isDirectory()).map((e) => e.name)) {
  if (name.startsWith(".") || name.startsWith("_")) continue;
  const dir = path.join(templatesDir, name);
  try {
    await fs.access(path.join(dir, "nexova.template.json"));
  } catch {
    continue;
  }
  const files = await walk(dir);
  const manifest = JSON.parse(files["nexova.template.json"].data);
  templates.push({ id: manifest.id, files });
  const bytes = Object.values(files).reduce((n, f) => n + f.data.length, 0);
  console.log(`bundled ${manifest.id}: ${Object.keys(files).length} files, ${Math.round(bytes / 1024)} KB`);
}
await fs.mkdir(path.dirname(outFile), { recursive: true });
// A TypeScript module rather than JSON: every bundler and Node itself load it without import attributes.
await fs.writeFile(outFile, `// Generated by scripts/bundle-templates.mjs. Do not edit.\nimport type { TemplateBundle } from "@nexova/engine";\nconst bundle: TemplateBundle = ${JSON.stringify({ generatedAt: new Date().toISOString(), templates })};\nexport default bundle;\n`);
console.log(`wrote ${path.relative(root, outFile)}`);
